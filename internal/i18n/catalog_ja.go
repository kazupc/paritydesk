package i18n

// Japanese text of the catalog. This is the only Go file that holds
// Japanese letters (a policy test enforces it). Keys are the constants of
// catalog.go in the same order (English-only ids left out), then the
// error catalog ids pderr.E<code>.title|safe|next in code order. Every
// format must use the same verbs per argument as the English text
// (explicit indexes such as %[2]s are allowed for word order); an
// incompatible entry is never used at run time (English is shown).
//
// Style (spec-i18n-ja 12.1):
//  1. Plain polite Japanese: statements 〜します。/〜しました。, requests
//     〜してください。, questions 〜しますか？. No exclamation marks, no
//     casual or over-honorific forms.
//  2. Short sentences, one fact each. An English semicolon between two
//     clauses becomes two sentences ending with 。.
//  3. Punctuation: 、 and 。; the question mark ？ followed by a half-width
//     space before "[y/N] ". A label at the start of a line takes a
//     half-width ": ". Table cells and column values (col.*, word.*,
//     profile.why.*, profile.problem.*) take no closing 。.
//  4. Full-width （） around Japanese content; half-width ( ) with a space
//     before them around ASCII-only content.
//  5. A half-width space between Japanese and any ASCII token or format
//     verb on both sides (プロファイル %s を, Claude が, %d 件), none next to
//     Japanese punctuation (%s、, （Claude).
//  6. Never full-width ASCII letters or digits, never half-width katakana.
//  7. Numbers: %d 件 for items, changes and entries; %d 世代 for a count of
//     generations; 世代 %d for generation number n; 1 つ, 1 行, 1 分.
//  8. Keep exactly: format verbs, command lines (paritydesk recover),
//     flags (--yes), backticked spans, "[y/N] ", DESTRUCTIVE, PD-E, docs
//     paths, environment variable names, file names, regular expressions,
//     leading indentation and trailing spaces.
//  9. Never advise ending an account's session (no sign-out or log-out
//     words); "stays signed in" is サインインしたままです.
// 10. Product names stay: Claude, Claude Code, Claude in Chrome, macOS,
//     Chrome, Local Storage, LevelDB, launchd, Homebrew, GitHub, Issue.
// 11. No personal names, no company names, no example people.
//
// Glossary (spec-i18n-ja 12.2): profile プロファイル; alias エイリアス;
// label ラベル; account アカウント; organization 組織; managed 管理対象の
// (managed by an employer or client: 勤務先や取引先が管理する); switch
// 切り替える / 切り替え; sync 同期; first sync 初回同期; sync base 同期ベース;
// carry 引き継ぐ; hand-off 受け渡し; plan 計画; preview 事前確認; apply
// 適用する; active 使用中の; previous 直前の; data folder データフォルダ;
// parked folder 待機中のフォルダ; marker マーカー; swap 入れ替え; swap-only
// mode 入れ替えのみのモード; generation 世代 / バックアップ世代; backup
// バックアップ; prune / purge 整理 / 全削除; restore 復元; rollback 元に戻す;
// recover 復旧; interrupted run 中断された実行; run / run id 実行 / 実行 ID;
// verify 検証; drift ずれ; conflict 競合; deletion 削除; destructive (prose)
// 削除を伴う; breaker / limit 上限; sign in サインイン; session / Code session
// セッション / Code セッション; the invoking session 切り替えを始めたセッション;
// worktree ワークツリー; uncommitted changes コミットされていない変更; config
// file 設定ファイル; default 既定値; state / state directory 状態 /
// 状態ディレクトリ; support archive サポート用アーカイブ; plugin / hook
// プラグイン / フック; background job バックグラウンドジョブ; read-only mode
// 読み取り専用モード; quit / launch / relaunch 終了 / 起動 / 再起動; force quit
// 強制終了; Automation permission オートメーションの許可; compatibility
// manifest 互換性マニフェスト; category カテゴリ; row 項目; sidebar / pin /
// section サイドバー / ピン留め / セクション; environment 環境; locale ロケール;
// Terminal / terminal ターミナル / 端末 (no terminal to ask: 確認できる端末);
